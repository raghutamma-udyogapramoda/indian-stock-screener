"""
Standardized Quantitative Strategy Interface and Pre-Built Strategy Library.
Provides deterministic signal generation, risk-governed position sizing, exit evaluation,
and dynamic AI rule configuration for Equities, Futures, and Multi-Leg Options.
"""

from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from datetime import datetime
from typing import Dict, List, Optional, Tuple, Any
import numpy as np
import pandas as pd

from core.indicators import enrich_with_indicators


@dataclass
class StrategyConfig:
    """Configurable operational parameters and risk boundaries for a strategy."""
    name: str = "Quantitative Strategy"
    version: str = "1.0.0"
    segment: str = "OPTIONS"  # "EQUITY", "FUTURES", "OPTIONS", "MULTI_LEG"
    option_strike_rule: str = "ATM"  # "ATM", "ITM_1", "OTM_1", "OTM_2"
    option_expiry_rule: str = "NEAR_MONTH"
    stop_loss_pct: float = 0.03
    target_pct: float = 0.06
    max_holding_bars: int = 10
    trail_stop_loss: bool = False
    custom_params: Dict[str, Any] = field(default_factory=dict)


@dataclass
class StrategySignal:
    """Actionable signal generated by a deterministic strategy."""
    timestamp: datetime
    symbol: str
    action: str  # "ENTER_LONG", "ENTER_SHORT", "EXIT"
    segment: str  # "EQUITY", "FUTURES", "OPTION_CE", "OPTION_PE", "BULL_CALL_SPREAD", "BEAR_PUT_SPREAD", "STRADDLE"
    strike_selection: str = "ATM"
    stop_loss_pct: float = 0.03
    target_pct: float = 0.06
    max_holding_bars: int = 10
    score: float = 1.0
    thesis: str = ""


class Strategy(ABC):
    """Abstract Strategy base class. Completely independent of UI and Streamlit."""

    def __init__(self, config: Optional[StrategyConfig] = None):
        self.config = config or StrategyConfig()
        self.name = self.config.name
        self.version = self.config.version

    @abstractmethod
    def generate_signals(
        self,
        market_data: pd.DataFrame,
        portfolio_state: Any,
        as_of_idx: int,
    ) -> Optional[StrategySignal]:
        """Generates signal using strictly data up to as_of_idx (Zero Look-Ahead Bias)."""
        pass

    @abstractmethod
    def evaluate_exit(
        self,
        position: Any,
        current_bar: pd.Series,
        market_data: pd.DataFrame,
        as_of_idx: int,
    ) -> Tuple[bool, str]:
        """Returns (should_exit, exit_reason)."""
        pass

    def calculate_position_size(
        self,
        signal: StrategySignal,
        portfolio_state: Any,
        lot_size: int = 1,
        risk_per_trade_pct: float = 0.02,
    ) -> int:
        """Determines lot count or share quantity based on capital risk."""
        cash = portfolio_state.cash
        if cash <= 0:
            return 0
        risk_budget = cash * risk_per_trade_pct
        est_sl_pts = signal.stop_loss_pct
        if est_sl_pts <= 0:
            est_sl_pts = 0.02
        # Position sizing: ensure risk does not exceed risk budget
        qty = max(lot_size, (lot_size * int(risk_budget / max(100.0, risk_budget * est_sl_pts))))
        return qty


class SupertrendBreakoutStrategy(Strategy):
    """
    Momentum trend-following strategy using Supertrend + EMA 20/50 alignment.
    Enters Long when Close crosses above Supertrend with expanding Volume.
    """

    def __init__(self, config: Optional[StrategyConfig] = None):
        cfg = config or StrategyConfig(
            name="Supertrend Trend Breakout",
            version="1.1.0",
            segment="OPTIONS",
            option_strike_rule="ATM",
            stop_loss_pct=0.025,
            target_pct=0.06,
            max_holding_bars=8,
        )
        super().__init__(cfg)

    def generate_signals(
        self,
        market_data: pd.DataFrame,
        portfolio_state: Any,
        as_of_idx: int,
    ) -> Optional[StrategySignal]:
        if as_of_idx < 30:
            return None

        # Look only at data up to as_of_idx
        df_slice = market_data.iloc[:as_of_idx + 1]
        curr = df_slice.iloc[-1]
        prev = df_slice.iloc[-2]

        close = float(curr["close"])
        supertrend = float(curr.get("supertrend", close * 0.98))
        prev_st = float(prev.get("supertrend", prev["close"]))
        ema20 = float(curr.get("ema_20", close))
        ema50 = float(curr.get("ema_50", close))
        rvol = float(curr.get("rvol_20", 1.0))
        rsi = float(curr.get("rsi_14", 50.0))

        # Bullish breakout: Price crosses above Supertrend with EMA alignment and healthy RSI
        is_bull_cross = (prev["close"] <= prev_st) and (close > supertrend) and (close >= ema20 >= ema50) and (rsi >= 52.0)
        # Bearish breakdown: Price crosses below Supertrend
        is_bear_cross = (prev["close"] >= prev_st) and (close < supertrend) and (close <= ema20 <= ema50) and (rsi <= 48.0)

        ts = df_slice.index[-1]
        sym = getattr(market_data, "symbol", "NIFTY")

        if is_bull_cross:
            seg = "OPTION_CE" if self.config.segment == "OPTIONS" else ("FUTURES" if self.config.segment == "FUTURES" else "EQUITY")
            return StrategySignal(
                timestamp=ts,
                symbol=sym,
                action="ENTER_LONG",
                segment=seg,
                strike_selection=self.config.option_strike_rule,
                stop_loss_pct=self.config.stop_loss_pct,
                target_pct=self.config.target_pct,
                max_holding_bars=self.config.max_holding_bars,
                thesis=f"Supertrend bullish crossover (Close ₹{close:,.1f} > ST ₹{supertrend:,.1f}) with EMA 20/50 alignment",
            )
        elif is_bear_cross:
            seg = "OPTION_PE" if self.config.segment == "OPTIONS" else ("FUTURES" if self.config.segment == "FUTURES" else "EQUITY")
            return StrategySignal(
                timestamp=ts,
                symbol=sym,
                action="ENTER_SHORT",
                segment=seg,
                strike_selection=self.config.option_strike_rule,
                stop_loss_pct=self.config.stop_loss_pct,
                target_pct=self.config.target_pct,
                max_holding_bars=self.config.max_holding_bars,
                thesis=f"Supertrend bearish breakdown (Close ₹{close:,.1f} < ST ₹{supertrend:,.1f}) with EMA 20/50 drag",
            )
        return None

    def evaluate_exit(
        self,
        position: Any,
        current_bar: pd.Series,
        market_data: pd.DataFrame,
        as_of_idx: int,
    ) -> Tuple[bool, str]:
        # 1. Holding period expiration
        bars_held = as_of_idx - position.entry_bar_idx
        if bars_held >= self.config.max_holding_bars:
            return True, f"Max holding period reached ({bars_held} bars)"

        # 2. P&L Stop Loss / Profit Target
        pnl_pct = position.unrealized_pnl_pct
        if pnl_pct <= -self.config.stop_loss_pct:
            return True, f"Stop Loss Triggered ({pnl_pct*100.0:+.2f}% <= {-self.config.stop_loss_pct*100.0:.2f}%)"
        if pnl_pct >= self.config.target_pct:
            return True, f"Profit Target Achieved ({pnl_pct*100.0:+.2f}% >= {self.config.target_pct*100.0:.2f}%)"

        # 3. Supertrend Trend Inversion Exit
        close = float(current_bar["close"])
        st = float(current_bar.get("supertrend", close))
        if position.is_long and close < st:
            return True, "Supertrend flipped Bearish"
        if (not position.is_long) and close > st:
            return True, "Supertrend flipped Bullish"

        return False, ""


class OptionsSpreadStrategy(Strategy):
    """
    Defined-risk multi-leg spread strategy.
    Enters Bull Call Spread on momentum breakouts and Bear Put Spread on breakdowns.
    Capping downside risk against theta erosion.
    """

    def __init__(self, config: Optional[StrategyConfig] = None):
        cfg = config or StrategyConfig(
            name="Defined-Risk Options Spreads",
            version="1.2.0",
            segment="MULTI_LEG",
            option_strike_rule="ATM",
            stop_loss_pct=0.03,
            target_pct=0.08,
            max_holding_bars=7,
        )
        super().__init__(cfg)

    def generate_signals(
        self,
        market_data: pd.DataFrame,
        portfolio_state: Any,
        as_of_idx: int,
    ) -> Optional[StrategySignal]:
        if as_of_idx < 25:
            return None

        df_slice = market_data.iloc[:as_of_idx + 1]
        curr = df_slice.iloc[-1]
        prev = df_slice.iloc[-2]

        close = float(curr["close"])
        high_20 = float(df_slice["high"].iloc[-21:-1].max()) if len(df_slice) > 21 else close
        low_20 = float(df_slice["low"].iloc[-21:-1].min()) if len(df_slice) > 21 else close
        rvol = float(curr.get("rvol_20", 1.0))

        ts = df_slice.index[-1]
        sym = getattr(market_data, "symbol", "NIFTY")

        # 20-day high breakout with volume expansion -> Bull Call Spread
        if close > high_20 and rvol >= 1.15:
            return StrategySignal(
                timestamp=ts,
                symbol=sym,
                action="ENTER_LONG",
                segment="BULL_CALL_SPREAD",
                strike_selection="ATM",
                stop_loss_pct=self.config.stop_loss_pct,
                target_pct=self.config.target_pct,
                max_holding_bars=self.config.max_holding_bars,
                thesis=f"20-day high breakout (₹{close:,.1f} > ₹{high_20:,.1f}) with RVOL {rvol:.2f}x -> Bull Call Spread",
            )
        # 20-day low breakdown with volume expansion -> Bear Put Spread
        elif close < low_20 and rvol >= 1.15:
            return StrategySignal(
                timestamp=ts,
                symbol=sym,
                action="ENTER_SHORT",
                segment="BEAR_PUT_SPREAD",
                strike_selection="ATM",
                stop_loss_pct=self.config.stop_loss_pct,
                target_pct=self.config.target_pct,
                max_holding_bars=self.config.max_holding_bars,
                thesis=f"20-day low breakdown (₹{close:,.1f} < ₹{low_20:,.1f}) with RVOL {rvol:.2f}x -> Bear Put Spread",
            )
        return None

    def evaluate_exit(
        self,
        position: Any,
        current_bar: pd.Series,
        market_data: pd.DataFrame,
        as_of_idx: int,
    ) -> Tuple[bool, str]:
        bars_held = as_of_idx - position.entry_bar_idx
        if bars_held >= self.config.max_holding_bars:
            return True, f"Expiry horizon elapsed ({bars_held} bars)"

        pnl_pct = position.unrealized_pnl_pct
        if pnl_pct <= -self.config.stop_loss_pct:
            return True, f"Spread Stop Loss Hit ({pnl_pct*100.0:+.2f}%)"
        if pnl_pct >= self.config.target_pct:
            return True, f"Spread Target Reached ({pnl_pct*100.0:+.2f}%)"

        return False, ""


class AIRuleStrategy(Strategy):
    """
    Dynamic AI-Assisted Strategy Rule Engine.
    Allows users and AI Advisors to propose custom technical conditions,
    risk parameters, and indicators and compile them into deterministic backtestable rules.
    """

    def __init__(
        self,
        name: str = "AI Dynamic Rule Strategy",
        rules: Optional[Dict[str, Any]] = None,
        segment: str = "OPTIONS",
        stop_loss_pct: float = 0.03,
        target_pct: float = 0.06,
        max_holding_bars: int = 10,
    ):
        r = rules or {}
        cfg = StrategyConfig(
            name=name,
            version="AI-1.0",
            segment=segment,
            stop_loss_pct=stop_loss_pct,
            target_pct=target_pct,
            max_holding_bars=max_holding_bars,
            custom_params=r,
        )
        super().__init__(cfg)
        self.rules = r

    def generate_signals(
        self,
        market_data: pd.DataFrame,
        portfolio_state: Any,
        as_of_idx: int,
    ) -> Optional[StrategySignal]:
        if as_of_idx < 30:
            return None

        df_slice = market_data.iloc[:as_of_idx + 1]
        curr = df_slice.iloc[-1]

        close = float(curr["close"])
        rsi = float(curr.get("rsi_14", 50.0))
        rvol = float(curr.get("rvol_20", 1.0))
        ema20 = float(curr.get("ema_20", close))

        # Evaluate configurable rules
        min_rsi = self.rules.get("min_rsi", 50.0)
        max_rsi = self.rules.get("max_rsi", 100.0)
        min_rvol = self.rules.get("min_rvol", 1.0)
        require_above_ema20 = self.rules.get("require_above_ema20", True)

        qualifies = (min_rsi <= rsi <= max_rsi) and (rvol >= min_rvol)
        if require_above_ema20 and close < ema20:
            qualifies = False

        if qualifies:
            ts = df_slice.index[-1]
            sym = getattr(market_data, "symbol", "NIFTY")
            action = self.rules.get("action", "ENTER_LONG")
            opt_type = self.rules.get("option_type", "OPTION_CE" if action == "ENTER_LONG" else "OPTION_PE")
            seg = opt_type if self.config.segment == "OPTIONS" else self.config.segment

            return StrategySignal(
                timestamp=ts,
                symbol=sym,
                action=action,
                segment=seg,
                strike_selection=self.config.option_strike_rule,
                stop_loss_pct=self.config.stop_loss_pct,
                target_pct=self.config.target_pct,
                max_holding_bars=self.config.max_holding_bars,
                thesis=f"AI Rule Matched: RSI {rsi:.1f} in [{min_rsi}, {max_rsi}], RVOL {rvol:.2f}x >= {min_rvol}x",
            )
        return None

    def evaluate_exit(
        self,
        position: Any,
        current_bar: pd.Series,
        market_data: pd.DataFrame,
        as_of_idx: int,
    ) -> Tuple[bool, str]:
        bars_held = as_of_idx - position.entry_bar_idx
        if bars_held >= self.config.max_holding_bars:
            return True, f"Max holding limit ({bars_held} bars)"

        pnl_pct = position.unrealized_pnl_pct
        if pnl_pct <= -self.config.stop_loss_pct:
            return True, f"AI Stop Loss Triggered ({pnl_pct*100.0:+.2f}%)"
        if pnl_pct >= self.config.target_pct:
            return True, f"AI Profit Target Reached ({pnl_pct*100.0:+.2f}%)"

        return False, ""


class BuiltinStrategies:
    """Registry of pre-configured quantitative strategies."""

    @classmethod
    def list_strategies(cls) -> Dict[str, str]:
        return {
            "SUPERTREND_BREAKOUT": "⚡ Supertrend Trend Breakout (Options CE/PE & Futures)",
            "DEFINED_RISK_SPREADS": "🛡️ Defined-Risk Options Spreads (Bull Call / Bear Put)",
            "RSI_PULLBACK": "🎯 RSI Reversal Dip Buyer (High-Quality Pullback)",
            "BTST_MOMENTUM": "🌅 BTST Overnight Momentum Continuation",
            "AI_CUSTOM_RULE": "🤖 AI-Discovered Dynamic Strategy Rule",
        }

    @classmethod
    def create(cls, strategy_id: str, **kwargs) -> Strategy:
        config = kwargs.get("config")
        rules = kwargs.get("rules", {})
        if strategy_id == "DEFINED_RISK_SPREADS":
            return OptionsSpreadStrategy(config=config)
        elif strategy_id == "AI_CUSTOM_RULE":
            rule_dict = rules if rules else {"min_rsi": 55.0, "max_rsi": 75.0, "min_rvol": 1.25, "action": "ENTER_LONG"}
            return AIRuleStrategy(name="AI Discovered Momentum Rule", rules=rule_dict)
        else:
            return SupertrendBreakoutStrategy(config=config)
